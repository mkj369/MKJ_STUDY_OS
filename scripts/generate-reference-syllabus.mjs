/**
 * Repeatable reference-syllabus import.
 *
 * Reads src/services/seed/data/referenceSyllabus.json (captured from the
 * reference site's public subject/chapter store) and regenerates BOTH:
 *   1. src/services/seed/referenceSyllabus.ts   — local-mode seed
 *   2. supabase/migrations/0009_reference_syllabus.sql — cloud-mode seed
 *
 * Deterministic UUIDs derive from the subject code + chapter index, so
 * re-running the import after a data correction updates rows in place and
 * never duplicates them or breaks user progress linked to chapter ids.
 *
 * Usage: node scripts/generate-reference-syllabus.mjs
 * After running: npm run test:db (parity test asserts SQL == TypeScript).
 */
import { readFileSync, writeFileSync } from 'node:fs';
import { createHash } from 'node:crypto';
import path from 'node:path';

const root = process.cwd();
const dataPath = path.join(root, 'src/services/seed/data/referenceSyllabus.json');
const data = JSON.parse(readFileSync(dataPath, 'utf8'));

/** Deterministic UUIDv4-shaped id from a stable key (same scheme as demo seed). */
function stableId(key) {
  const hex = createHash('sha256').update(`mkj-reference-syllabus:${key}`).digest('hex');
  return [
    hex.slice(0, 8),
    hex.slice(8, 12),
    '4' + hex.slice(13, 16),
    '8' + hex.slice(17, 20),
    hex.slice(20, 32),
  ].join('-');
}

const meta = data.meta;
const total = data.subjects.reduce((n, s) => n + s.chapters.length, 0);
if (total !== meta.chapter_total_expected) {
  throw new Error(`Chapter count mismatch: found ${total}, expected ${meta.chapter_total_expected}. Refusing to generate.`);
}
const seen = new Set();
for (const s of data.subjects) {
  if (seen.has(s.code)) throw new Error(`Duplicate subject code ${s.code}`);
  seen.add(s.code);
  if (s.chapters.length === 0) throw new Error(`Subject ${s.code} has no chapters`);
}

const versionId = stableId('version:hsc-science-reference');
const checked = meta.captured_at;
const now = `${checked}T00:00:00.000Z`;
const authority = 'HSC Study Tracker (community reference)';
const title = `HSC Science — reference tracker syllabus (${meta.academic_year})`;
const versionLabel = 'hsc-science-reference-tracker-2026';
const note =
  `Imported ${checked} from ${meta.source} (public subject/chapter store). ` +
  '13 subject papers, 128 chapters, titles and order preserved verbatim. ' +
  'The source covers HSC Science only — no SSC, other groups, batches or topic breakdowns were available. ' +
  'Not yet compared with official NCTB textbooks; every row stays needs_verification until a human checks it.';

const version = {
  id: versionId,
  authority,
  country: 'Bangladesh',
  education_level: meta.education_level,
  class_grade: 'Class 11–12',
  stream: meta.stream,
  academic_year: meta.academic_year,
  version_label: versionLabel,
  title,
  source_url: meta.source,
  scope: 'exam_syllabus',
  source_checked_at: checked,
  source_note: note,
  verification_status: 'needs_verification',
  is_demo: false,
  created_at: now,
  updated_at: now,
};

const subjects = [];
const chapters = [];
data.subjects.forEach((s, si) => {
  const sid = stableId(`subject:${s.code}`);
  subjects.push({
    id: sid,
    curriculum_version_id: versionId,
    name: s.name,
    name_bn: s.name_bn,
    code: s.code,
    paper_label: s.paper_label,
    is_compulsory: s.is_compulsory,
    sort_order: si + 1,
    verification_status: 'needs_verification',
    source_url: meta.data_url,
    created_at: now,
  });
  s.chapters.forEach((titleText, ci) => {
    chapters.push({
      id: stableId(`chapter:${s.code}:${ci + 1}`),
      curriculum_subject_id: sid,
      parent_id: null,
      title: titleText,
      title_bn: titleText,
      chapter_number: String(ci + 1),
      sort_order: ci + 1,
      source_url: meta.data_url,
      verification_status: 'needs_verification',
      is_demo: false,
      created_at: now,
    });
  });
});

/* ---------------- TypeScript seed ---------------- */
const ts = `/**
 * AUTO-GENERATED by scripts/generate-reference-syllabus.mjs — do not edit by hand.
 * Source data: src/services/seed/data/referenceSyllabus.json (edit that, then regenerate).
 *
 * HSC Science chapter syllabus imported from the reference tracker
 * (${meta.source}) on ${checked}. Titles and ordering are verbatim;
 * verification_status is needs_verification everywhere (community source,
 * not yet compared with the official NCTB textbooks). HSC Admission reuses
 * these same rows — nothing is duplicated per track.
 */
import type { CurriculumChapter, CurriculumSubject, CurriculumVersion } from '@/types/domain';

export const REFERENCE_VERSION: CurriculumVersion = ${JSON.stringify(version, null, 2)};

export const REFERENCE_SUBJECTS: CurriculumSubject[] = ${JSON.stringify(subjects, null, 2)};

export const REFERENCE_CHAPTERS: CurriculumChapter[] = ${JSON.stringify(chapters, null, 2)};

export const REFERENCE_CURRICULUM = {
  versions: [REFERENCE_VERSION],
  subjects: REFERENCE_SUBJECTS,
  chapters: REFERENCE_CHAPTERS,
};
`;
writeFileSync(path.join(root, 'src/services/seed/referenceSyllabus.ts'), ts);

/* ---------------- SQL migration ---------------- */
const q = (v) => {
  if (v === null || v === undefined) return 'null';
  if (typeof v === 'boolean') return v ? 'true' : 'false';
  if (typeof v === 'number') return String(v);
  return `'${String(v).replace(/'/g, "''")}'`;
};
const row = (vals) => `  (${vals.map(q).join(', ')})`;

const versionCols = ['id', 'authority', 'country', 'education_level', 'class_grade', 'stream', 'academic_year', 'version_label', 'title', 'source_url', 'scope', 'source_checked_at', 'source_note', 'verification_status', 'is_demo'];
const subjectCols = ['id', 'curriculum_version_id', 'name', 'name_bn', 'code', 'paper_label', 'is_compulsory', 'sort_order', 'verification_status', 'source_url'];
const chapterCols = ['id', 'curriculum_subject_id', 'parent_id', 'title', 'title_bn', 'chapter_number', 'sort_order', 'source_url', 'verification_status', 'is_demo'];

const sql = `-- ---------------------------------------------------------------------------
-- 0009 — HSC Science reference-tracker syllabus (AUTO-GENERATED)
--
-- Generated by scripts/generate-reference-syllabus.mjs from
-- src/services/seed/data/referenceSyllabus.json. Do not edit by hand.
--
-- SOURCE
--   ${meta.source} — public subject/chapter store, captured ${checked}.
--   ${meta.scope_notes}
--
-- DATA SAFETY
--   * Deterministic UUIDs + on-conflict upsert: re-running never duplicates.
--   * No student table is touched; existing progress keeps its ids.
--   * Every row is needs_verification (community source, NCTB unchecked).
--   * HSC Admission reuses these HSC rows; no per-track copies.
-- ---------------------------------------------------------------------------

insert into public.curriculum_versions
  (${versionCols.join(', ')})
values
${row(versionCols.map((c) => version[c]))}
on conflict (id) do update set
  authority = excluded.authority,
  title = excluded.title,
  source_url = excluded.source_url,
  scope = excluded.scope,
  source_checked_at = excluded.source_checked_at,
  source_note = excluded.source_note,
  verification_status = excluded.verification_status,
  updated_at = now();

insert into public.curriculum_subjects
  (${subjectCols.join(', ')})
values
${subjects.map((s) => row(subjectCols.map((c) => s[c]))).join(',\n')}
on conflict (id) do update set
  name = excluded.name,
  name_bn = excluded.name_bn,
  code = excluded.code,
  paper_label = excluded.paper_label,
  is_compulsory = excluded.is_compulsory,
  sort_order = excluded.sort_order,
  verification_status = excluded.verification_status,
  source_url = excluded.source_url;

insert into public.curriculum_chapters
  (${chapterCols.join(', ')})
values
${chapters.map((c) => row(chapterCols.map((k) => c[k]))).join(',\n')}
on conflict (id) do update set
  title = excluded.title,
  title_bn = excluded.title_bn,
  chapter_number = excluded.chapter_number,
  sort_order = excluded.sort_order,
  source_url = excluded.source_url,
  verification_status = excluded.verification_status;
`;
writeFileSync(path.join(root, 'supabase/migrations/0009_reference_syllabus.sql'), sql);

console.log(`Generated: 1 version, ${subjects.length} subjects, ${chapters.length} chapters.`);
console.log(`Version id: ${versionId}`);
